
from flask import Flask, request, jsonify
import pickle
import numpy as np
import os

app = Flask(__name__)

# Get the directory where this script is located
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# Model path - try multiple possible locations
model_paths = [
    os.path.join(BASE_DIR, 'lr_pkl (2)'),
    os.path.join(BASE_DIR, 'lr_pkl'),
    os.path.join(BASE_DIR, 'gradient_boosting_model.pkl'),
    os.path.join(BASE_DIR, 'gradient_boosting_model.pkl')
]

model = None
model_path_used = None

for path in model_paths:
    if os.path.exists(path):
        try:
            with open(path, 'rb') as f:
                model = pickle.load(f)
            model_path_used = path
            print(f"Model loaded successfully from: {path}")
            break
        except Exception as e:
            print(f"Failed to load model from {path}: {e}")
            continue

if model is None:
    print("WARNING: No model could be loaded!")

# Categorical mappings
fuel_dict = {"Petrol": 0, "Diesel": 1, "CNG": 2, "LPG": 3, "Electric": 4}
seller_dict = {"Dealer": 0, "Individual": 1, "Trustmark Dealer": 2}
transmission_dict = {"Manual": 0, "Automatic": 1}
owner_dict = {
    "First Owner": 0, 
    "Second Owner": 1, 
    "Third Owner": 2, 
    "Fourth & Above Owner": 3, 
    "Test Drive Car": 4
}

@app.route('/predict', methods=['POST'])
def predict():
    if model is None:
        return jsonify({'error': 'Model not loaded'}), 500
    
    try:
        data = request.get_json()
        
        # Extract features from request
        year = int(data.get('year', 2020))
        km_driven = float(data.get('km_driven', 0))
        fuel = data.get('fuel', 'Petrol')
        seller_type = data.get('seller_type', 'Individual')
        transmission = data.get('transmission', 'Manual')
        owner = data.get('owner', 'First Owner')
        mileage = float(data.get('mileage', 0))
        engine = float(data.get('engine', 0))
        max_power = float(data.get('max_power', 0))
        seats = int(data.get('seats', 5))
        
        # Convert categorical to numerical
        fuel_val = fuel_dict.get(fuel, 0)
        seller_val = seller_dict.get(seller_type, 1)
        transmission_val = transmission_dict.get(transmission, 0)
        owner_val = owner_dict.get(owner, 0)
        
        # Create feature array - matching training data format
        # Features: [name(0), year, selling_price, km_driven, fuel, seller_type, transmission, owner, mileage, engine, max_power, seats]
        # Note: The first column (name) is typically dropped or set to 0
        input_data = np.array([[
            0,  # Placeholder for name/car brand
            year,
            0,  # selling_price placeholder (we're predicting this)
            km_driven,
            fuel_val,
            seller_val,
            transmission_val,
            owner_val,
            mileage,
            engine,
            max_power,
            seats
        ]])
        
        # Make prediction
        prediction = model.predict(input_data)
        
        # Ensure prediction is positive
        predicted_price = max(0, float(prediction[0]))
        
        return jsonify({
            'success': True,
            'predicted_price': round(predicted_price, 2),
            'currency': '₹'
        })
        
    except Exception as e:
        return jsonify({'error': str(e)}), 400

@app.route('/health', methods=['GET'])
def health():
    return jsonify({
        'status': 'healthy',
        'model_loaded': model is not None,
        'model_path': model_path_used
    })

if __name__ == '__main__':
    print("Starting Car Price Prediction API...")
    print(f"Model loaded: {model is not None}")
    if model_path_used:
        print(f"Model path: {model_path_used}")
    app.run(host='0.0.0.0', port=5000, debug=True)

